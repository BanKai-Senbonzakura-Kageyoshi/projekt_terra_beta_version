    BookingCreateView,
    BookingManageView,
    BookingDecisionView,
    BookingReleaseTableView,
    ContactPageView,
    EventRequestCreateView,
    EventsPageView,
    GalleryPageView,
    HomePageView,
    MenuPageView,
    MenuCategoryCreateView,
    MenuItemCreateView,
    MenuManageView,
    OwnerLoginView,
    OwnerDashboardView,
    PrivacyPageView,
    RegisterView,
